#!/usr/bin/env python3
"""Patch layout of present_transfer's frame, shared by the guest and the checker.

The frame is 1280x720 A8R8G8B8_SRGB, 8 columns by 4 rows of 160x180 patches.
Each patch has one sRGB-encoded 8-bit colour. Run with --header to write the
guest's C table (src/patches.h).

The reference reproduces shadPS4's post-process pass (post_process.frag) on the
CPU: the sampler decodes sRGB to linear, the optional Rec.709 curve encodes
with the BT.709 OETF and decodes that as sRGB, and the pass encodes sRGB with
gamma 1.0 for an 8-bit UNORM swapchain.
"""
from __future__ import annotations

import sys

WIDTH, HEIGHT = 1280, 720
COLUMNS, ROWS = 8, 4
PATCH_W, PATCH_H = WIDTH // COLUMNS, HEIGHT // ROWS

_GRAYS = [0, 1, 2, 4, 8, 12, 16, 24, 32, 48, 64, 80, 96, 112, 128, 144,
          160, 176, 192, 208, 224, 240, 250, 255]
_COLOURS = [(64, 0, 0), (0, 128, 0), (0, 0, 192), (200, 100, 50),
            (10, 20, 30), (255, 128, 0), (30, 60, 240), (90, 200, 160)]
# (r, g, b), row-major
PATCHES = [(g, g, g) for g in _GRAYS] + _COLOURS
assert len(PATCHES) == COLUMNS * ROWS


def patch_centre(index: int) -> tuple[int, int]:
    col, row = index % COLUMNS, index // COLUMNS
    return col * PATCH_W + PATCH_W // 2, row * PATCH_H + PATCH_H // 2


def srgb_eotf(v: float) -> float:
    return v / 12.92 if v <= 0.04045 else ((v + 0.055) / 1.055) ** 2.4


def srgb_oetf(l: float) -> float:
    return 12.92 * l if l < 0.0031308 else 1.055 * l ** (1 / 2.4) - 0.055


def rec709_oetf(l: float) -> float:
    return 4.5 * l if l < 0.018 else 1.099 * l ** 0.45 - 0.099


def reference(value: int, rec709: bool) -> int:
    l = srgb_eotf(value / 255.0)
    if rec709:
        l = srgb_eotf(rec709_oetf(l))
    out = min(max(srgb_oetf(l), 0.0), 1.0)
    return int(out * 255.0 + 0.5)


def header() -> str:
    rows = ",\n    ".join(f"{{{r}, {g}, {b}}}" for r, g, b in PATCHES)
    return (
        "/* Generated by tools/patches.py --header; do not edit. */\n"
        "#ifndef PRESENT_TRANSFER_PATCHES_H\n#define PRESENT_TRANSFER_PATCHES_H\n\n"
        "#include <stdint.h>\n\n"
        f"enum {{ FRAME_W = {WIDTH}, FRAME_H = {HEIGHT}, PATCH_COLUMNS = {COLUMNS}, "
        f"PATCH_ROWS = {ROWS}, PATCH_W = {PATCH_W}, PATCH_H = {PATCH_H} }};\n\n"
        f"static const uint8_t patch_rgb[{len(PATCHES)}][3] = {{\n    {rows},\n}};\n\n"
        "#endif\n"
    )


if __name__ == "__main__":
    if sys.argv[1:] == ["--header"]:
        sys.stdout.write(header())
    else:
        for i, rgb in enumerate(PATCHES):
            print(i, rgb, [reference(c, False) for c in rgb], [reference(c, True) for c in rgb])
