#!/usr/bin/env python3
"""Writes src/fixtures.h: small PNG files and the RGBA pixels they decode to.

The PNGs are built here from a fixed pixel pattern with zlib, so the test has no
image assets of unknown origin. Run from any directory:

    python3 tests/hle_png/tools/gen_fixtures.py
"""
from __future__ import annotations

from pathlib import Path
import struct
import zlib

WIDTH = 5
HEIGHT = 4

# Adam7 passes: (x0, y0, dx, dy).
ADAM7 = [(0, 0, 8, 8), (4, 0, 8, 8), (0, 4, 4, 8), (2, 0, 4, 4), (0, 2, 2, 4), (1, 0, 2, 2), (0, 1, 1, 2)]


def pixel(x: int, y: int) -> tuple[int, int, int, int]:
    return (10 + 40 * x, 20 + 50 * y, 17 * (x + y), 255 - 10 * x - 5 * y)


def chunk(kind: bytes, data: bytes) -> bytes:
    crc = zlib.crc32(kind + data) & 0xFFFFFFFF
    return struct.pack(">I", len(data)) + kind + data + struct.pack(">I", crc)


def scanlines(xs: list[int], ys: list[int], channels: int) -> bytes:
    out = bytearray()
    for y in ys:
        out.append(0)  # filter type None
        for x in xs:
            out.extend(pixel(x, y)[:channels])
    return bytes(out)


def png(color_type: int, interlace: bool) -> bytes:
    channels = 4 if color_type == 6 else 3
    ihdr = struct.pack(">IIBBBBB", WIDTH, HEIGHT, 8, color_type, 0, 0, 1 if interlace else 0)
    if interlace:
        raw = b""
        for x0, y0, dx, dy in ADAM7:
            xs = list(range(x0, WIDTH, dx))
            ys = list(range(y0, HEIGHT, dy))
            if xs and ys:
                raw += scanlines(xs, ys, channels)
    else:
        raw = scanlines(list(range(WIDTH)), list(range(HEIGHT)), channels)
    return (
        b"\x89PNG\r\n\x1a\n"
        + chunk(b"IHDR", ihdr)
        + chunk(b"IDAT", zlib.compress(raw, 9))
        + chunk(b"IEND", b"")
    )


def c_bytes(name: str, data: bytes) -> str:
    rows = [", ".join(f"0x{b:02x}" for b in data[i : i + 12]) for i in range(0, len(data), 12)]
    body = ",\n    ".join(rows)
    return f"static const uint8_t {name}[{len(data)}] = {{\n    {body},\n}};\n"


def main() -> None:
    rgba = bytes(c for y in range(HEIGHT) for x in range(WIDTH) for c in pixel(x, y))
    parts = [
        "/* Generated by tools/gen_fixtures.py; do not edit. */\n",
        "#ifndef HLE_PNG_FIXTURES_H\n#define HLE_PNG_FIXTURES_H\n\n#include <stdint.h>\n\n",
        f"enum {{ FIXTURE_WIDTH = {WIDTH}, FIXTURE_HEIGHT = {HEIGHT} }};\n\n",
        "/* 8-bit RGBA, not interlaced. */\n" + c_bytes("png_rgba", png(6, False)) + "\n",
        "/* 8-bit RGB, not interlaced: decodes with the caller's alpha value. */\n"
        + c_bytes("png_rgb", png(2, False))
        + "\n",
        "/* 8-bit RGBA, Adam7 interlaced. */\n" + c_bytes("png_rgba_adam7", png(6, True)) + "\n",
        "/* The pixels of every fixture as R, G, B, A rows (A of png_rgb aside). */\n"
        + c_bytes("pixels_rgba", rgba)
        + "\n",
        "#endif\n",
    ]
    out = Path(__file__).resolve().parent.parent / "src" / "fixtures.h"
    out.write_text("".join(parts), encoding="utf-8")


if __name__ == "__main__":
    main()
